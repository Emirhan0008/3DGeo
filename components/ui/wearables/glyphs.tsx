export type GlyphKey = keyof typeof GLYPHS;

export function hasGlyph(key: string): key is GlyphKey {
  return Object.prototype.hasOwnProperty.call(GLYPHS, key);
}

/** Renders one content glyph on the shared 24×24 engraved grid. */
export function Glyph({
  name,
  className = '',
  strokeWidth = 1.5,
}: {
  name: string;
  className?: string;
  strokeWidth?: number;
}) {
  const def = GLYPHS[name] ?? GLYPHS.compass;
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
      focusable="false"
    >
      {def.f?.map((d, i) => (
        <path key={`f${i}`} d={d} fill="currentColor" fillOpacity={0.22} stroke="none" />
      ))}
      {def.s?.map((d, i) => (
        <path key={`s${i}`} d={d} />
      ))}
    </svg>
  );
}
